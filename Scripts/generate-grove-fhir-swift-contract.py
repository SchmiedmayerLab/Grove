def healthkit_source_type_name(identifier: str) -> str:
    """`HKQuantityTypeIdentifierVO2Max` reads as `vo2Max`, `HKWorkoutTypeIdentifier` as `workout`."""
    match = SOURCE_TYPE_IDENTIFIER.match(identifier)
    if match is None:
        raise ValueError(f"cannot derive a Swift case from HealthKit identifier {identifier!r}")
    suffix = match.group(2) or match.group(1)
    acronym = LEADING_ACRONYM.match(suffix)
    if acronym:
        return acronym.group(1).lower() + suffix[acronym.end():]
    return suffix[:1].lower() + suffix[1:]


def producer_rule_lines(exchange_protocol: dict) -> list[str]:
    rows = exchange_protocol["producerDiagnostics"]
    codes = [row["code"] for row in rows]
    if len(codes) != len(set(codes)):
        raise ValueError("producer diagnostic codes must be unique")
    cases: dict[str, str] = {}
    for code in codes:
        name = swift_name(code)
        if name in cases:
            raise ValueError(f"producer diagnostics {cases[name]!r} and {code!r} generate the same Swift case")
        cases[name] = code
    severities = {row.get("severity", "error") for row in rows}
    if not severities <= {"error", "warning"}:
        raise ValueError(f"unknown producer diagnostic severity: {sorted(severities - {'error', 'warning'})}")
    lines = [
        "/// Every registered Grove producer rule, generated from exchange-protocol.json.",
        "public enum ExchangeGraphRule: String, CaseIterable, Sendable {",
    ]
    for row in rows:
        lines.append(f"    case {swift_name(row['code'])} = {swift_string(row['code'])}")
    lines.extend([
        "",
        "    /// The registry's reason, verbatim.",
        "    public var reason: String {",
        "        switch self {",
    ])
    for row in rows:
        lines.append(f"        case .{swift_name(row['code'])}:")
        lines.append(f"            {swift_string(row['reason'])}")
    lines.extend([
        "        }",
        "    }",
        "",
        "    /// A warning names what an accepted record lost; every other rule refuses the record or graph.",
        "    public var severity: ProducerDiagnostic.Severity {",
        "        switch self {",
    ])
    warnings = [row for row in rows if row.get("severity", "error") == "warning"]
    errors = [row for row in rows if row.get("severity", "error") != "warning"]
    for group, severity in ((warnings, ".warning"), (errors, ".error")):
        if not group:
            continue
        names = ", ".join(f".{swift_name(row['code'])}" for row in group)
        lines.append(f"        case {names}:")
        lines.append(f"            {severity}")
    lines.extend([
        "        }",
        "    }",
        "}",
        "",
        "",
    ])
    return lines


