def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog-directory", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("Sources/GroveFHIRContract/Generated.swift"),
    )
    parser.add_argument(
        "--healthkit-output",
        type=Path,
        default=Path("Sources/GroveHealthKitFHIR/HealthKitSourceType.swift"),
    )
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    outputs = {
        arguments.output: generate(arguments.catalog_directory),
        arguments.healthkit_output: generate_healthkit(arguments.catalog_directory),
    }
    if arguments.check:
        stale = [
            path for path, generated in outputs.items()
            if (path.read_text(encoding="utf-8") if path.exists() else "") != generated
        ]
        for path in stale:
            print(f"error: {path} is not synchronized with the grove-fhir catalogs", file=sys.stderr)
        return 1 if stale else 0
    for path, generated in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
