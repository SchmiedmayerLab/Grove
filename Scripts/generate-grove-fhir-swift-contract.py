def generate_healthkit(catalog_directory: Path) -> str:
    """The HealthKit-typed half of the contract: the source-type inventory and the ECG claim, `internal` to the
    HealthKit adapter, so the compiler checks every HealthKit SDK spelling the guide states."""
    healthkit_catalog = load_catalog(catalog_directory / "healthkit-adapter.json")
    package_graph = load_catalog(catalog_directory / "package-graph.json")
    measurement_catalog = load_catalog(catalog_directory / "measurement-catalog.json")
    sensor_catalog = load_catalog(catalog_directory / "sensor-catalog.json")
    loinc_concepts = load_concepts(catalog_directory / "terminology" / "loinc-concepts.json")
    identifiers = [row["sourceTypeIdentifier"] for row in healthkit_catalog["rows"]]
    source_type_cases: dict[str, str] = {}
    names: dict[str, str] = {}
    for identifier in identifiers:
        name = healthkit_source_type_name(identifier)
        if name in names:
            raise ValueError(f"HealthKit identifiers {names[name]!r} and {identifier!r} generate the same Swift case")
        names[name] = identifier
        source_type_cases[identifier] = name
    lines = [
        HEALTHKIT_HEADER,
        "/// Every source type in the HealthKit adapter inventory, generated from healthkit-adapter.json.",
        "public enum HealthKitSourceType: String, CaseIterable, Sendable {",
    ]
    for identifier in identifiers:
        lines.append(f"    case {source_type_cases[identifier]} = {swift_string(identifier)}")
    lines.extend([
        "",
        "    /// The inventory row of a sample's type, or `nil` for a type the inventory does not list.",
        "    public init?(_ sample: HKSample) {",
        "        self.init(rawValue: sample.sampleType.identifier)",
        "    }",
        "}",
        "",
        "",
    ])
    members = profile_members(package_graph)
    measurements = measurement_catalog["measurements"]
    lines.extend(code_display_lines(healthkit_catalog, measurements, loinc_concepts))
    ecg_claim = healthkit_catalog["sensorAdapterClaims"]["electrocardiogram"]
    lines.extend(electrocardiogram_claim_lines(
        ecg_claim,
        waveform_code=electrocardiogram_waveform_code(ecg_claim, sensor_catalog["contracts"], loinc_concepts),
        measurement_members=measurement_members(measurements, measurement_canonicals(package_graph, measurements)),
        source_type_cases=source_type_cases,
        profile_reference=lambda canonical: members.get(canonical, swift_string(canonical)),
    ))
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def component_result_code_system(component: dict) -> str | None:
    """The guide names a component's result CodeSystem with the last segment of its bound ValueSet."""
    value_set = component.get("valueSet")
    if not component.get("resultCodes") or not value_set:
        return None
    if "/ValueSet/" not in value_set:
        raise ValueError(f"component valueSet is not a Grove canonical: {value_set!r}")
    return value_set.replace("/ValueSet/", "/CodeSystem/")


def quantity_contract_expression(quantity: dict) -> str:
    if not all(isinstance(quantity.get(key), str) for key in QUANTITY_KEYS):
        raise ValueError(f"a quantity must state its system, code and unit: {quantity!r}")
    domain = quantity.get("valueDomain")
    rendered_domain = "nil"
    if domain:
        minimum = domain["minimum"]
        maximum = domain.get("maximum")
        rendered_maximum = (
            "QuantityBoundary("
            f"value: {swift_string(json.dumps(maximum['value'], allow_nan=False))}, "
            f"inclusive: {str(maximum['inclusive']).lower()})"
        ) if maximum else "nil"
        rendered_domain = (
            "QuantityValueDomain("
            "minimum: QuantityBoundary("
            f"value: {swift_string(json.dumps(minimum['value'], allow_nan=False))}, "
            f"inclusive: {str(minimum['inclusive']).lower()}), "
            f"maximum: {rendered_maximum}, "
            f"integerOnly: {str(domain['integerOnly']).lower()})"
        )
    return (
        "QuantityContract("
        f"system: {swift_string(quantity['system'])}, "
        f"code: {swift_string(quantity['code'])}, "
        f"unit: {swift_string(quantity['unit'])}, "
        f"valueDomain: {rendered_domain})"
    )


def coding_contract_expression(coding: dict) -> str:
    if not isinstance(coding.get("system"), str) or not isinstance(coding.get("code"), str):
        raise ValueError(f"a coding must state its system and code: {coding!r}")
    display = f", display: {swift_string(coding['display'])}" if coding.get("display") else ""
    return (
        "CodingContract("
        f"system: {swift_string(coding['system'])}, "
        f"code: {swift_string(coding['code'])}{display})"
    )


def measurement_lines(
    measurement: dict, access: str = "public", profile_expression: str | None = None
) -> list[str]:
    """`profile_expression` is the Swift expression of the measurement's profile; by default the generated
    `Profile` member it names."""
    rendered_profile = profile_expression or f"Profile.{swift_name(measurement['profile'])}"
    lines = [
        f"    {access} static let {swift_name(measurement['id'])} = MeasurementContract(",
        f"        id: {swift_string(measurement['id'])},",
        f"        profile: {rendered_profile},",
        f"        code: {coding_contract_expression(measurement['code'])},",
    ]
    required_codings = measurement.get("requiredCodings", [])
    if required_codings:
        lines.append("        requiredCodings: [")
        for required_coding in required_codings:
            lines.append(f"            {coding_contract_expression(required_coding)},")
        lines.append("        ],")
    else:
        lines.append("        requiredCodings: [],")
    quantity = measurement.get("quantity")
    if quantity:
        lines.append(f"        quantity: {quantity_contract_expression(quantity)},")
    else:
        lines.append("        quantity: nil,")
    components = measurement.get("components", [])
    if components:
        lines.append("        components: [")
        for component in components:
            quantity = component.get("quantity")
            rendered_quantity = quantity_contract_expression(quantity) if quantity else "nil"
            rendered_result_codes = ", ".join(
                "ResultCodeContract("
                f"code: {swift_string(result_code['code'])}, "
                f"display: {swift_string(result_code['display'])})"
                for result_code in component.get("resultCodes", [])
            )
            result_code_system = component_result_code_system(component)
            lines.append(
                "            ComponentContract("
                f"id: {swift_string(component['id'])}, "
                f"system: {swift_string(component['system'])}, "
                f"code: {swift_string(component['code'])}, "
                f"quantity: {rendered_quantity}, "
                f"resultCodeSystem: "
                f"{swift_string(result_code_system) if result_code_system else 'nil'}, "
                f"resultCodes: [{rendered_result_codes}]),"
            )
        lines.append("        ],")
    else:
        lines.append("        components: [],")
    result_code_system = measurement.get("resultCodeSystem")
    lines.append(
        f"        resultCodeSystem: {swift_string(result_code_system) if result_code_system else 'nil'},"
    )
    allowed_values = measurement.get("allowedValues", [])
    if allowed_values:
        values = ", ".join(swift_string(value) for value in allowed_values)
        lines.append(f"        allowedValues: [{values}],")
    else:
        lines.append("        allowedValues: [],")
    result_codes = measurement.get("resultCodes", [])
    if result_codes:
        lines.append("        resultCodes: [")
        for result_code in result_codes:
            lines.append(
                "            ResultCodeContract("
                f"code: {swift_string(result_code['code'])}, "
                f"display: {swift_string(result_code['display'])}),"
            )
        lines.append("        ],")
    else:
        lines.append("        resultCodes: [],")
    method = measurement.get("method")
    if method:
        lines.append(
            "        method: MethodContract("
            f"code: {swift_string(method['code'])}, "
            f"display: {swift_string(method['display'])}),"
        )
    else:
        lines.append("        method: nil,")
    method_choice = measurement.get("methodChoice", [])
    if method_choice:
        values = ", ".join(swift_string(value) for value in method_choice)
        lines.append(f"        methodChoice: [{values}],")
    else:
        lines.append("        methodChoice: [],")
    effective = {
        "dateTime": "dateTime",
        "Period": "period",
        "dateTime-or-Period": "dateTimeOrPeriod",
    }.get(measurement["effective"])
    if effective is None:
        raise ValueError(
            f"measurement {measurement['id']!r} has unsupported effective choice "
            f"{measurement['effective']!r}"
        )
    lines.append(f"        effective: .{effective},")
    category = measurement.get("category")
    lines.append(f"        category: {coding_contract_expression(category) if category is not None else 'nil'}")
    lines.extend(["    )", ""])
    return lines


def profile_members(package_graph: dict) -> dict[str, str]:
    """Canonical profile URL -> its generated `Profile` member, so rows and claims reference the constants the
    contract defines instead of repeating the literal."""
    return {
        f"{package['canonical']}/StructureDefinition/{profile}": f"Profile.{swift_name(profile)}"
        for package in package_graph["packages"]
        for profile in package["profiles"]
    }


def measurement_canonicals(package_graph: dict, measurements: list[dict]) -> list[str]:
    """Each measurement's profile canonical, in catalog order, under the package of the measurement's owner."""
    packages = {package["source"]: package["canonical"] for package in package_graph["packages"]}
    canonicals = []
    for measurement in measurements:
        owner = measurement.get("owner", "mobile")
        if owner not in packages:
            raise ValueError(f"measurement {measurement['id']!r} is owned by {owner!r}, which no package declares")
        canonicals.append(f"{packages[owner]}/StructureDefinition/{measurement['profile']}")
    return canonicals


def measurement_members(measurements: list[dict], canonicals: list[str]) -> dict[str, tuple[str, dict]]:
    """Profile canonical -> (generated member, measurement) for every measurement a generated catalog lists, so a
    claim that reuses a measurement names it."""
    members: dict[str, tuple[str, dict]] = {}
    for measurement, canonical in zip(measurements, canonicals, strict=True):
        catalog = MEASUREMENT_CATALOGS.get(measurement.get("owner", "mobile"))
        if catalog is None:
            continue
        if canonical in members:
            raise ValueError(
                f"measurements {members[canonical][1]['id']!r} and {measurement['id']!r} both claim {canonical}"
            )
        members[canonical] = (f"{catalog[0]}.{swift_name(measurement['id'])}", measurement)
    return members


def loinc_display(coding: dict, concepts: dict, label: str) -> str:
    """The display the guide's LOINC concept catalog states for a LOINC coding."""
    concept = concepts.get(coding.get("code")) if coding.get("system") == LOINC_SYSTEM else None
    if not isinstance(concept, dict) or not isinstance(concept.get("display"), str):
        raise ValueError(f"{label} code {coding!r} is no LOINC concept the guide's terminology catalog displays")
    return concept["display"]


def code_display_lines(healthkit_catalog: dict, measurements: list[dict], concepts: dict) -> list[str]:
    """The guide's display of each code a HealthKit row's measurement states without one, from the LOINC concept
    catalog, keyed by the code exactly as the measurement states it. A row's measurement is a catalog measurement or
    a standard adapter claim (body-mass index); a sensor adapter claim states its codes itself, and a row naming
    neither is a defect the content compiler reports."""
    named = {measurement["id"]: measurement for measurement in measurements}
    named.update(healthkit_catalog["standardAdapterClaims"])
    displays: dict[tuple[str, str], str] = {}
    for row in healthkit_catalog["rows"]:
        for measurement_id in row["measurementIDs"]:
            code = named.get(measurement_id, {}).get("code")
            if code is not None and not code.get("display"):
                displays[(code["system"], code["code"])] = loinc_display(code, concepts, measurement_id)
    return [
        "/// The guide's display of each code a HealthKit row's measurement states without one, generated from the",
        "/// guide's LOINC concept catalog (terminology/loinc-concepts.json) and keyed by the code exactly as the",
        "/// measurement states it.",
        "enum HealthKitTerminology {",
        "    /// The display of each such code.",
        "    static let displays: [CodingContract: String] = [",
        *(
            f"        {coding_contract_expression({'system': system, 'code': code})}: {swift_string(display)},"
            for (system, code), display in sorted(displays.items())
        ),
        "    ]",
        "}",
        "",
        "",
    ]


def electrocardiogram_waveform_code(ecg_claim: dict, sensor_contracts: list[dict], concepts: dict) -> dict:
    """The waveform's code, which the HealthKit claim does not restate: the code of the sensor contract whose
    profile the claim's first profile is, with the display the guide's LOINC concept catalog states."""
    profile = ecg_claim["profiles"][0]
    contracts = [contract for contract in sensor_contracts if contract.get("profile") == profile]
    if len(contracts) != 1 or not isinstance(contracts[0].get("code"), dict):
        raise ValueError(f"HealthKit ECG profile {profile!r} is no single coded sensor contract's")
    code = contracts[0]["code"]
    return {**code, "display": code.get("display") or loinc_display(code, concepts, "HealthKit ECG waveform")}


def electrocardiogram_outputs(ecg_claim: dict) -> dict[str, dict]:
    """The ECG claim's outputs by role: exactly the waveform and the average heart rate."""
    outputs: dict[str, dict] = {}
    for output in ecg_claim["outputs"]:
        role = output["outputRole"]
        if role not in ELECTROCARDIOGRAM_OUTPUT_ROLES:
            raise ValueError(f"HealthKit ECG output role {role!r} is not one of {list(ELECTROCARDIOGRAM_OUTPUT_ROLES)}")
        if role in outputs:
            raise ValueError(f"HealthKit ECG output role {role!r} is declared twice")
        outputs[role] = output
    missing = [role for role in ELECTROCARDIOGRAM_OUTPUT_ROLES if role not in outputs]
    if missing:
        raise ValueError(f"HealthKit ECG claim declares no {missing} output")
    if outputs["electrocardiogram"]["profiles"] != ecg_claim["profiles"]:
        raise ValueError("HealthKit ECG waveform output must claim exactly the ECG claim's profiles")
    return outputs


def average_heart_rate_member(output: dict, measurement_members: dict[str, tuple[str, dict]]) -> str:
    """The generated member of the measurement whose code and quantity the average heart rate states, which is
    the measurement its first profile claims."""
    profile = next(iter(output.get("profiles") or []), None)
    member, measurement = measurement_members.get(profile, (None, None))
    if measurement is None:
        raise ValueError(f"HealthKit ECG average heart rate profile {profile!r} is no generated measurement's")
    code, expected_code = output.get("code") or {}, measurement["code"]
    if (
        (code.get("system"), code.get("code")) != (expected_code["system"], expected_code["code"])
        or expected_code.get("display") not in (None, code.get("display"))
    ):
        raise ValueError(
            f"HealthKit ECG average heart rate code {code!r} is not {measurement['id']!r}'s code {expected_code!r}"
        )
    quantity = output.get("quantity")
    expected_quantity = {key: (measurement.get("quantity") or {}).get(key) for key in QUANTITY_KEYS}
    if not isinstance(quantity, dict) or quantity != expected_quantity:
        raise ValueError(
            f"HealthKit ECG average heart rate quantity {quantity!r} is not exactly {measurement['id']!r}'s "
            f"system, code and unit {expected_quantity!r}"
        )
    return member


def closed_value_mapping_lines(name: str, mapping: dict) -> list[str]:
    """One closed mapping as its CodeSystem and a dictionary keyed by the HealthKit SDK value it maps."""
    key_type = ELECTROCARDIOGRAM_VALUE_MAPPINGS[name]
    if not isinstance(mapping.get("system"), str) or not mapping.get("values"):
        raise ValueError(f"HealthKit ECG {name!r} mapping must state its system and map at least one source value")
    keys: dict[str, str] = {}
    for value in mapping["values"]:
        source, code = value.get("sourceValue"), value.get("code")
        if not isinstance(source, str) or not isinstance(code, str):
            raise ValueError(
                f"HealthKit ECG {name!r} mapping must map a string source value to a string code: {value!r}"
            )
        if key_type == "Int":
            if not CANONICAL_INTEGER.fullmatch(source):
                raise ValueError(f"HealthKit ECG {name!r} source value {source!r} is not a canonical decimal integer")
            key = source
        else:
            if not SWIFT_CASE_NAME.fullmatch(source) or source in SWIFT_RESERVED_NAMES:
                raise ValueError(f"HealthKit ECG {name!r} source value {source!r} cannot name a {key_type} case")
            key = f"{key_type}.{source}"
        if key in keys:
            raise ValueError(f"HealthKit ECG {name!r} mapping maps source value {source!r} twice")
        keys[key] = code
    return [
        f"    /// The CodeSystem of the {mapping['r4Element']} code each {mapping['sourceField']} maps to.",
        f"    static let {name}System = {swift_string(mapping['system'])}",
        f"    /// The {mapping['r4Element']} code of each {mapping['sourceField']} the guide admits.",
        f"    static let {name}Codes: [{key_type}: String] = [",
        *(f"        {key}: {swift_string(code)}," for key, code in keys.items()),
        "    ]",
    ]


def correlated_symptom_cases(identifiers: list[str], source_type_cases: dict[str, str]) -> list[str]:
    """The `HealthKitSourceType` case of each symptom type an ECG may reference, in catalog order."""
    if not identifiers:
        raise ValueError("HealthKit ECG claim admits no correlated symptom source type")
    cases: list[str] = []
    for identifier in identifiers:
        if identifier not in source_type_cases:
            raise ValueError(f"HealthKit ECG symptom source type {identifier!r} is not an inventory row")
        if source_type_cases[identifier] in cases:
            raise ValueError(f"HealthKit ECG symptom source type {identifier!r} is listed twice")
        cases.append(source_type_cases[identifier])
    return cases


def electrocardiogram_claim_lines(
    ecg_claim: dict,
    waveform_code: dict,
    measurement_members: dict[str, tuple[str, dict]],
    source_type_cases: dict[str, str],
    profile_reference: Callable[[str], str],
) -> list[str]:
    """The ECG claim typed against the HealthKit SDK, `internal` to the adapter: its outputs, the waveform's code,
    the average heart rate's code and measurement, the lead and its coding, the voltage unit, each closed value
    mapping and the correlated symptom types."""
    outputs = electrocardiogram_outputs(ecg_claim)
    average_heart_rate = outputs["average-heart-rate"]
    measurement_member = average_heart_rate_member(average_heart_rate, measurement_members)
    source_lead = ecg_claim.get("sourceLead")
    lead = SOURCE_LEAD.fullmatch(str(source_lead))
    if lead is None or lead.group("case") in SWIFT_RESERVED_NAMES:
        raise ValueError(f"HealthKit ECG source lead {source_lead!r} is no HKElectrocardiogram.Lead case")
    mappings = ecg_claim["closedValueMappings"]
    if set(mappings) != set(ELECTROCARDIOGRAM_VALUE_MAPPINGS):
        raise ValueError(
            f"HealthKit ECG closed value mappings {sorted(mappings)} are not exactly "
            f"{sorted(ELECTROCARDIOGRAM_VALUE_MAPPINGS)}"
        )
    symptom_cases = correlated_symptom_cases(
        ecg_claim["correlatedSymptomEvidence"]["sourceTypes"], source_type_cases
    )
    lines = [
        "/// The HealthKit electrocardiogram claim, generated from healthkit-adapter.json sensorAdapterClaims and",
        "/// typed against the HealthKit SDK, so the compiler checks the guide's spelling of every HealthKit value.",
        "@available(iOS 18, macOS 15, watchOS 11, *)",
        "enum HealthKitElectrocardiogramClaim {",
        "    /// One output the claim declares.",
        "    struct Output: Sendable {",
        "        /// The output role.",
        "        let role: String",
        "        /// The output discriminator.",
        "        let discriminator: String",
        "        /// The output's exact direct `meta.profile` claim.",
        "        let profiles: [FHIRPrimitive<Canonical>]",
        "    }",
        "",
        "    /// The waveform Observation.",
        "    static let waveform = Output(",
        f"        role: {swift_string(outputs['electrocardiogram']['outputRole'])},",
        f"        discriminator: {swift_string(outputs['electrocardiogram']['outputDiscriminator'])},",
        "        profiles: HealthKitContract.electrocardiogramProfiles",
        "    )",
        "    /// The waveform's code: the code of the sensor contract its first profile is, with the guide's display.",
        f"    static let waveformCode = {coding_contract_expression(waveform_code)}",
        "    /// The average-heart-rate Observation, derived from the waveform.",
        "    static let averageHeartRate = Output(",
        f"        role: {swift_string(average_heart_rate['outputRole'])},",
        f"        discriminator: {swift_string(average_heart_rate['outputDiscriminator'])},",
        f"        profiles: [{', '.join(profile_reference(profile) for profile in average_heart_rate['profiles'])}]",
        "    )",
        "    /// The average heart rate's code, with the guide's display.",
        f"    static let averageHeartRateCode = {coding_contract_expression(average_heart_rate['code'])}",
        "    /// The measurement whose code, category and quantity the average heart rate states (the claim's code",
        "    /// adds the display). Its effective choice is not the claim's: the average heart rate always states",
        "    /// the waveform's exact effectivePeriod.",
        f"    static let averageHeartRateMeasurement = {measurement_member}",
        "    /// The lead whose voltages the waveform carries.",
        f"    static let sourceLead = {source_lead}",
        "    /// The coding of that lead on the waveform component.",
        f"    static let leadCode = {coding_contract_expression(ecg_claim['leadCode'])}",
        "    /// The unit of the waveform's voltages.",
        f"    static let voltageQuantity = {quantity_contract_expression(ecg_claim['quantity'])}",
    ]
    for name in ELECTROCARDIOGRAM_VALUE_MAPPINGS:
        lines.extend(closed_value_mapping_lines(name, mappings[name]))
    lines.extend([
        "    /// The symptom source types an ECG may reference through Observation.hasMember.",
        "    static let correlatedSymptomSourceTypes: Set<HealthKitSourceType> = [",
        *(f"        .{case}," for case in symptom_cases),
        "    ]",
        "}",
        "",
    ])
    return lines


def load_catalog(path: Path) -> dict:
    with path.open(encoding="utf-8") as file:
        value = json.load(file)
    if value.get("fhirVersion") != "4.0.1":
        raise ValueError(f"{path} is not an R4 (4.0.1) catalog")
    return value


def load_concepts(path: Path) -> dict:
    """The concepts of one of the guide's terminology catalogs, by code."""
    with path.open(encoding="utf-8") as file:
        concepts = json.load(file).get("concepts")
    if not isinstance(concepts, dict):
        raise ValueError(f"{path} states no concepts")
    return concepts


