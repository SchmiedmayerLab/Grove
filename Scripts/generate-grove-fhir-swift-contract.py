def swift_name(value: str) -> str:
    words = [word for word in re.split(r"[^A-Za-z0-9]+", value) if word]
    if not words:
        raise ValueError(f"cannot derive a Swift name from {value!r}")
    first, *rest = words
    name = first.lower() + "".join(word[:1].upper() + word[1:] for word in rest)
    if name[:1].isdigit():
        name = "value" + name
    return name


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


