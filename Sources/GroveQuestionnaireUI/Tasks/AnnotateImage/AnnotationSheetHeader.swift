#if canImport(UIKit)
import SwiftUI


@available(iOS 18, macOS 15, watchOS 11, *)
struct AnnotationSheetHeader: View {
    let title: String
    let subtitle: String

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(title)
                .font(.headline)
            if !subtitle.isEmpty {
                Text(subtitle)
                    .font(.subheadline)
                    .foregroundStyle(.secondary)
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .padding(.horizontal, 16)
        .padding(.vertical, 12)
        .annotationGlassPanel(cornerRadius: 20)
        .accessibilityIdentifier("AnnotationPrompt")
    }
}
#endif
